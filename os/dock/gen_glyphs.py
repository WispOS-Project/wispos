#!/usr/bin/env python3
"""Writes os/dock/glyphs.h: the alpha masks of the icon set at the sizes the shell draws, rendered by the code of mockup.py (the glyphs of the locked pictures) exactly as its Canvas.icon()
does (supersampled 4x, Lanczos down), so the shell's icons are the pictures' icons.

  gen_glyphs.py            rewrites glyphs.h
  gen_glyphs.py --check    exits 1 when glyphs.h is not what this script would write (the tests run it)

The battery's fill and the wifi and volume levels are separate masks or are drawn by the shell, so the header holds one mask per (name, size, level)."""
import argparse, sys
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import mockup

APPS = ('apps', 'browser', 'terminal', 'settings', 'game', 'images', 'monitor', 'about')
# (glyph, sizes, levels): the sizes it is drawn at in mockup.py
WANT = [(a, (18, 22, 44), (0,)) for a in APPS] + [
    ('pin', (14, 18), (0,)), ('wifi', (18, 20), (0, 1, 2, 3)), ('volume', (18, 20), (0, 1, 2)), ('battery', (18, 20), (0,)),
    ('brightness', (18,), (0,)), ('bluetooth', (18,), (0,)), ('ssh', (18,), (0,)), ('usb', (18,), (0,)),
    ('power', (18,), (0,)), ('sleep', (18,), (0,)), ('restart', (18,), (0,)),
    ('left', (18, 22), (0,)), ('right', (18, 22), (0,)), ('up', (22,), (0,)), ('down', (22,), (0,)), ('close', (18,), (0,)),
]


def battery_outline(d, u):
    """mockup.g_battery without its fill (the shell draws the fill at the charge level)."""
    mockup._rr(d, (2.2 * u, 6.6 * u, 20.2 * u, 17.4 * u), 1.8 * u, outline=255, width=int(1.8 * u))
    d.rectangle((20.9 * u, 10 * u, 22.4 * u, 14 * u), fill=255)


def mask(name, size, level):
    big = Image.new('L', (size * mockup.SS, size * mockup.SS), 0)
    d, u = ImageDraw.Draw(big), size * mockup.SS / 24.0
    if name == 'battery': battery_outline(d, u)
    elif name == 'wifi': mockup.g_wifi(d, u, level=level)
    elif name == 'volume': mockup.g_volume(d, u, level=level)
    else: mockup.GLYPHS[name](d, u)
    return np.asarray(big.resize((size, size), Image.LANCZOS), np.uint8)


def render():
    out = ['/* The icon set as alpha masks (8 bit, row by row) at the sizes the desktop shell draws, generated by os/dock/gen_glyphs.py from the glyph code of os/dock/mockup.py.',
           ' * Do not edit: change the glyph in mockup.py and run the script (os/test_dock_view.py fails while this file is stale). */',
           '#ifndef WISPOS_DOCK_GLYPHS_H', '#define WISPOS_DOCK_GLYPHS_H', '', '#include <stdint.h>', '',
           'typedef struct { const char *name; int size, level; const uint8_t *a; } GlyphMask;', '']
    table = []
    for name, sizes, levels in WANT:
        for size in sizes:
            for level in levels:
                m = mask(name, size, level)
                sym = 'gm_%s_%d_%d' % (name, size, level)
                flat = m.flatten()
                rows = [', '.join('%d' % v for v in flat[i:i + size]) for i in range(0, len(flat), size)]
                out.append('static const uint8_t %s[%d] = {\n    %s\n};' % (sym, len(flat), ',\n    '.join(rows)))
                table.append('    { "%s", %d, %d, %s },' % (name, size, level, sym))
    out += ['', 'static const GlyphMask GLYPH_MASKS[] = {'] + table + ['};', '#define GLYPH_MASK_COUNT ((int)(sizeof GLYPH_MASKS / sizeof *GLYPH_MASKS))', '', '#endif', '']
    return '\n'.join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0]); ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text = render(); target = HERE / 'glyphs.h'
    if a.check:
        if not target.exists() or target.read_text() != text:
            print('glyphs.h is stale: run os/dock/gen_glyphs.py', file=sys.stderr); return 1
        return 0
    target.write_text(text); print('wrote %s: %d masks, %d bytes' % (target, text.count('static const uint8_t'), len(text))); return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
